#!/usr/bin/env node
/*
 * Scans public/blogs/articles/*.xml and derives:
 *   - src/data/blogs.generated.js  (internal blog cards for the blog list/homepage)
 *   - public/sitemap.xml           (one <url> entry per article, plus the homepage)
 * Also validates that every referenced image (thumbnail + inline <img>) exists
 * under public/. Missing images are reported as warnings, not build failures,
 * since asset creation is a separate manual step.
 */
const fs = require("fs");
const path = require("path");

const ROOT_DIR = path.resolve(__dirname, "..");
const ARTICLES_DIR = path.join(ROOT_DIR, "public", "blogs", "articles");
const PUBLIC_DIR = path.join(ROOT_DIR, "public");
const GENERATED_DATA_FILE = path.join(
  ROOT_DIR,
  "src",
  "data",
  "blogs.generated.js",
);
const SITEMAP_FILE = path.join(ROOT_DIR, "public", "sitemap.xml");
const SITE_ORIGIN = "https://sandeeptiwari.me";

function extractTag(xml, tagName) {
  const match = xml.match(new RegExp(`<${tagName}>([\\s\\S]*?)</${tagName}>`));
  return match ? match[1].replace(/\s+/g, " ").trim() : "";
}

function extractAttr(xml, tagName, attrName) {
  const match = xml.match(
    new RegExp(`<${tagName}\\b[^>]*\\b${attrName}="([^"]*)"`),
  );
  return match ? match[1] : "";
}

function extractAllImageSrcs(xml) {
  const srcs = [];
  const regex = /<(?:img|thumbnail)\b[^>]*\bsrc="([^"]+)"/g;
  let match;
  while ((match = regex.exec(xml)) !== null) {
    srcs.push(match[1]);
  }
  return srcs;
}

function parseArticle(filePath) {
  const xml = fs.readFileSync(filePath, "utf8");
  const metaMatch = xml.match(/<meta>([\s\S]*?)<\/meta>/);
  const meta = metaMatch ? metaMatch[1] : "";

  const slug = extractTag(meta, "slug") || path.basename(filePath, ".xml");
  const title = extractTag(meta, "title");
  const category = extractTag(meta, "category");
  const readTime = extractTag(meta, "readTime");
  const summary = extractTag(meta, "summary");
  const date = extractTag(meta, "date");
  const thumbnail = extractAttr(meta, "thumbnail", "src");

  return {
    slug,
    title,
    category,
    readTime,
    summary,
    date,
    thumbnail,
    imageSrcs: extractAllImageSrcs(xml),
  };
}

function validateImages(articles) {
  const missing = [];
  articles.forEach((article) => {
    article.imageSrcs.forEach((src) => {
      const relativePath = src.replace(/^\//, "");
      const absolutePath = path.join(PUBLIC_DIR, relativePath);
      if (!fs.existsSync(absolutePath)) {
        missing.push({ slug: article.slug, src });
      }
    });
  });
  return missing;
}

function writeGeneratedBlogsData(articles) {
  const entries = articles
    .map(
      (a) => `  {
    url: "/blogs/${a.slug}",
    title: ${JSON.stringify(a.title)},
    description: ${JSON.stringify(a.summary)},
    category: ${JSON.stringify(a.category)},
    readTime: ${JSON.stringify(a.readTime)},
  },`,
    )
    .join("\n");

  const content = `// AUTO-GENERATED by scripts/generate-blog-manifest.js — do not edit manually.
const internalBlogs = [
${entries}
];

export { internalBlogs };
`;
  fs.writeFileSync(GENERATED_DATA_FILE, content, "utf8");
}

function writeSitemap(articles) {
  const today = new Date().toISOString().slice(0, 10);
  const urlEntries = articles
    .map((a) => {
      const lastmod = a.date
        ? `${a.date}T00:00:00+00:00`
        : `${today}T00:00:00+00:00`;
      return `
<url>
  <loc>${SITE_ORIGIN}/blogs/${a.slug}</loc>
  <lastmod>${lastmod}</lastmod>
</url>
`;
    })
    .join("\n");

  const content = `<?xml version="1.0" encoding="UTF-8"?>
<urlset
      xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"
      xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
      xsi:schemaLocation="http://www.sitemaps.org/schemas/sitemap/0.9
            http://www.sitemaps.org/schemas/sitemap/0.9/sitemap.xsd">

<url>
  <loc>${SITE_ORIGIN}/</loc>
  <lastmod>${today}T00:00:00+00:00</lastmod>
</url>
${urlEntries}
</urlset>
`;
  fs.writeFileSync(SITEMAP_FILE, content, "utf8");
}

function main() {
  if (!fs.existsSync(ARTICLES_DIR)) {
    console.warn(
      `[blog-manifest] No articles directory found at ${ARTICLES_DIR}, skipping.`,
    );
    return;
  }

  const files = fs
    .readdirSync(ARTICLES_DIR)
    .filter((f) => f.endsWith(".xml"))
    .sort();

  const articles = files.map((f) => parseArticle(path.join(ARTICLES_DIR, f)));

  writeGeneratedBlogsData(articles);
  writeSitemap(articles);

  const missingImages = validateImages(articles);
  if (missingImages.length > 0) {
    console.warn(
      `[blog-manifest] WARNING: ${missingImages.length} referenced image(s) are missing under public/:`,
    );
    missingImages.forEach(({ slug, src }) =>
      console.warn(`  - [${slug}] ${src}`),
    );
  }

  console.log(
    `[blog-manifest] Generated ${articles.length} internal blog entr${
      articles.length === 1 ? "y" : "ies"
    } and updated sitemap.xml.`,
  );
}

main();
